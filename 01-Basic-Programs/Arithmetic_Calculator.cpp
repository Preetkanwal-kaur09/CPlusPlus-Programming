#include <iostream>
using namespace std;
int main()
{
    int a, b, sum, sub, multi, divide, modu;
    cout<<"Enter two numbers: ";
    cin>>a>>b;
    sum = a + b;
    sub = a - b;
    multi = a * b;
    divide = a / b;
    modu = a % b;
    cout<<"Addition: "<<sum<<endl;
    cout<<"Substraction: "<<sub<<endl;
    cout<<"Multiplication: "<<multi<<endl;
    cout<<"Division: "<<divide<<endl;
    cout<<"Modulus: "<<modu;
    
    
    
    

    return 0;
}
